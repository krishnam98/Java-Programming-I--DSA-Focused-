public class binaryoperators {
    public static void main(String args[]){
        System.out.println(5&6); //binary and
        System.out.println(5|4); //binary or
        System.out.println(5^6); //binary xor 
        System.out.println(~5);   //binary one's compliment
        System.out.println(5<<2); //binary left shift
        System.out.println(6>>2); //binary right shift


    }
    
}
